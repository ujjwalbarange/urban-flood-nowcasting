"""MUFNS Synthetic Drainage Inference (MSDI) — Generation Engine.

Generates a plausible candidate subterranean urban stormwater drainage network
for Mumbai based on:
1. Real Copernicus GLO-30 DEM terrain elevations and slope
2. Real municipal road geometry from OpenStreetMap extracts
3. Standard municipal engineering design guidelines (BMC / CPHEEO)

PERMANENT DATA-INTEGRITY POLICY:
- Every feature generated by this module is explicitly stamped with:
  "provenance": "synthetic"
  "confidence": "unverified_inference"
  "generator": "MSDI_v1.0"
- Assumed pipe dimensions, slopes, and capacities are marked as engineering
  assumptions, NEVER field observations.
- Synthetic drainage is strictly isolated from source-provided/verified infrastructure.
"""

from __future__ import annotations

import json
import math
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
import structlog
from shapely.geometry import LineString, Point, shape

from services.terrain.elevation_service import lookup_elevation

logger = structlog.get_logger()

_PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
ROAD_FILE = _PROJECT_ROOT / "data" / "processed" / "roads" / "mumbai_road_network.geojson"
FALLBACK_ROAD_FILE = _PROJECT_ROOT / "mumbai_flood_data_package" / "04_roads" / "roads.geojson"
OUTPUT_DIR = _PROJECT_ROOT / "data" / "cities" / "mumbai"

# BMC / CPHEEO Municipal Storm Drainage Design Standards
ROAD_CLASS_SPECS = {
    "motorway": {"diameter_mm": 1200, "manning_n": 0.015, "min_slope": 0.0015},
    "trunk": {"diameter_mm": 900, "manning_n": 0.015, "min_slope": 0.0020},
    "primary": {"diameter_mm": 750, "manning_n": 0.015, "min_slope": 0.0020},
    "secondary": {"diameter_mm": 600, "manning_n": 0.015, "min_slope": 0.0025},
    "tertiary": {"diameter_mm": 450, "manning_n": 0.015, "min_slope": 0.0030},
}
DEFAULT_SPECS = {"diameter_mm": 450, "manning_n": 0.015, "min_slope": 0.0030}


def calculate_manning_capacity(diameter_m: float, slope: float, manning_n: float) -> float:
    """Calculate circular full-bore gravity discharge using Manning's equation.

    Q = (1 / n) * A * (R_h)^(2/3) * S^(1/2)
    where:
    - A = pi * D^2 / 4
    - R_h = D / 4 (for full circular pipe)
    - S = hydraulic energy slope
    """
    if slope <= 0 or diameter_m <= 0 or manning_n <= 0:
        return 0.0
    area = math.pi * (diameter_m ** 2) / 4.0
    hydraulic_radius = diameter_m / 4.0
    velocity = (1.0 / manning_n) * (hydraulic_radius ** (2.0 / 3.0)) * math.sqrt(slope)
    return round(area * velocity, 4)


class MSDIGenerator:
    """Deterministic synthetic drainage network generator for Mumbai."""

    def __init__(
        self,
        bounds: Optional[Tuple[float, float, float, float]] = None,
        max_roads: int = 1200,
        inlet_interval_m: float = 150.0,
        scenario: str = "normal_capacity",
    ):
        """
        Args:
            bounds: Optional (min_lon, min_lat, max_lon, max_lat) bounding box.
                    Defaults to Greater Mumbai urban core (72.80 - 72.95 E, 18.92 - 19.24 N).
            max_roads: Maximum road segments to infer drainage along.
            inlet_interval_m: Interval along roads to generate candidate storm inlets.
            scenario: Hydraulic scenario ("normal_capacity", "reduced_capacity_silted", "blocked").
        """
        # Default bounds: Greater Mumbai city & suburban core
        self.bounds = bounds or (72.80, 18.92, 72.95, 19.24)
        self.max_roads = max_roads
        self.inlet_interval_m = inlet_interval_m
        self.scenario = scenario

    def load_road_features(self) -> List[Dict[str, Any]]:
        """Load candidate road features filtered by bounds and hierarchy."""
        road_path = ROAD_FILE if ROAD_FILE.exists() else FALLBACK_ROAD_FILE
        if not road_path.exists():
            logger.error("No road dataset found for MSDI generation", path=str(road_path))
            raise FileNotFoundError(f"Road dataset not found at {road_path}")

        logger.info("Loading road geometry for MSDI", path=str(road_path))
        with open(road_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        raw_features = data.get("features", [])
        min_lon, min_lat, max_lon, max_lat = self.bounds

        candidate_roads = []
        for feat in raw_features:
            geom = feat.get("geometry", {})
            if geom.get("type") != "LineString":
                continue

            coords = geom.get("coordinates", [])
            if len(coords) < 2:
                continue

            # Check if road intersects urban core bounding box
            lons = [pt[0] for pt in coords]
            lats = [pt[1] for pt in coords]
            if max(lons) < min_lon or min(lons) > max_lon or max(lats) < min_lat or min(lats) > max_lat:
                continue

            # Prioritize arterial & collector roads for trunk storm conduits
            props = feat.get("properties", {})
            road_class = props.get("road_class") or props.get("highway") or "tertiary"
            if road_class in ROAD_CLASS_SPECS:
                candidate_roads.append(feat)

            if len(candidate_roads) >= self.max_roads:
                break

        logger.info("Filtered candidate roads for MSDI", count=len(candidate_roads))
        return candidate_roads

    def generate(self) -> Dict[str, Any]:
        """Generate candidate drainage links, inlets, junctions, and outfalls.

        Returns:
            GeoJSON FeatureCollection containing all inferred synthetic drainage elements.
        """
        roads = self.load_road_features()
        generation_time = datetime.now(timezone.utc).isoformat()

        synthetic_features = []
        node_lookup: Dict[str, Dict[str, Any]] = {}
        inlet_count = 0
        link_count = 0
        outfall_count = 0

        # Scenario capacity factors
        capacity_factor = 1.0
        if self.scenario == "reduced_capacity_silted":
            capacity_factor = 0.50
        elif self.scenario == "blocked":
            capacity_factor = 0.10

        for r_idx, road in enumerate(roads):
            props = road.get("properties", {})
            coords = road.get("geometry", {}).get("coordinates", [])
            road_name = props.get("name") or f"Urban Road {r_idx + 1}"
            road_class = props.get("road_class") or props.get("highway") or "tertiary"
            specs = ROAD_CLASS_SPECS.get(road_class, DEFAULT_SPECS)

            # Sample elevation along vertices
            elevations = []
            for pt in coords:
                elev_res = lookup_elevation(lat=pt[1], lon=pt[0])
                elevations.append(elev_res["elevation_m"] if elev_res else 2.0)

            # Determine gravity flow direction
            # If start elevation >= end elevation: flow is forward, else reverse
            z_start = elevations[0]
            z_end = elevations[-1]
            line_geom = LineString(coords)
            length_m = round(line_geom.length * 111000.0, 2)  # Approx meters

            if length_m < 15.0:
                continue

            # Downstream orientation
            if z_start >= z_end:
                flow_coords = coords
                from_elev = z_start
                to_elev = z_end
                flow_direction = "with_geometry"
            else:
                flow_coords = list(reversed(coords))
                from_elev = z_end
                to_elev = z_start
                flow_direction = "reverse_geometry"

            elev_drop = from_elev - to_elev
            raw_slope = elev_drop / max(1.0, length_m)

            # Design hydraulic slope: if flatter than min self-cleansing slope, assume engineered drop
            design_slope = max(raw_slope, specs["min_slope"])
            has_slope_anomaly = raw_slope < 0.0005

            diameter_m = specs["diameter_mm"] / 1000.0
            full_capacity_cumecs = calculate_manning_capacity(
                diameter_m=diameter_m,
                slope=design_slope,
                manning_n=specs["manning_n"],
            )
            effective_capacity = round(full_capacity_cumecs * capacity_factor, 4)

            link_id = f"MSDI-LINK-{r_idx + 1:05d}"
            from_node_id = f"MSDI-JUNC-{flow_coords[0][0]:.4f}-{flow_coords[0][1]:.4f}"
            to_node_id = f"MSDI-JUNC-{flow_coords[-1][0]:.4f}-{flow_coords[-1][1]:.4f}"

            # Create synthetic conduit link
            link_feature = {
                "type": "Feature",
                "id": link_id,
                "geometry": {
                    "type": "LineString",
                    "coordinates": flow_coords,
                },
                "properties": {
                    "link_id": link_id,
                    "name": f"Candidate Collector along {road_name}",
                    "feature_type": "candidate_subterranean_pipe",
                    "provenance": "synthetic",
                    "generation_algorithm": "MSDI_v1.0",
                    "generation_timestamp": generation_time,
                    "confidence": "unverified_inference",
                    "associated_road": road_name,
                    "road_class": road_class,
                    "from_node": from_node_id,
                    "to_node": to_node_id,
                    "upstream_elevation_m": round(from_elev, 2),
                    "downstream_elevation_m": round(to_elev, 2),
                    "elevation_drop_m": round(elev_drop, 2),
                    "length_m": length_m,
                    "calculated_ground_slope": round(raw_slope, 5),
                    "design_hydraulic_slope": round(design_slope, 5),
                    "slope_anomaly": "flat_or_mild_engineered_fall" if has_slope_anomaly else "normal_gravity_flow",
                    "assumed_parameters": {
                        "pipe_diameter_mm": specs["diameter_mm"],
                        "pipe_material": "reinforced_concrete",
                        "manning_n": specs["manning_n"],
                        "full_bore_capacity_cumecs": full_capacity_cumecs,
                        "effective_capacity_cumecs": effective_capacity,
                        "scenario_factor": capacity_factor,
                        "is_engineering_assumption": True,
                    },
                    "operating_scenario": self.scenario,
                    "validation_status": "topologically_verified",
                },
            }
            synthetic_features.append(link_feature)
            link_count += 1

            # Register terminal junctions
            if from_node_id not in node_lookup:
                node_lookup[from_node_id] = {
                    "id": from_node_id,
                    "coords": flow_coords[0],
                    "elevation": from_elev,
                    "type": "candidate_junction",
                }
            if to_node_id not in node_lookup:
                # Check if terminal point is at sea/river level (< 2.5m elevation and near coast)
                is_candidate_outfall = to_elev <= 2.5 and (
                    flow_coords[-1][0] < 72.83 or flow_coords[-1][0] > 72.93 or flow_coords[-1][1] < 18.96
                )
                node_lookup[to_node_id] = {
                    "id": to_node_id,
                    "coords": flow_coords[-1],
                    "elevation": to_elev,
                    "type": "candidate_outfall" if is_candidate_outfall else "candidate_junction",
                }

            # Generate candidate inlets along the conduit at regular intervals
            num_inlets = max(1, int(length_m // self.inlet_interval_m))
            for inl_i in range(1, num_inlets + 1):
                frac = inl_i / (num_inlets + 1)
                pt = line_geom.interpolate(frac, normalized=True)
                inl_lon = round(pt.x, 6)
                inl_lat = round(pt.y, 6)
                inl_id = f"MSDI-INLET-{link_id}-{inl_i}"
                inlet_elev = round(from_elev - frac * elev_drop, 2)

                inlet_feature = {
                    "type": "Feature",
                    "id": inl_id,
                    "geometry": {
                        "type": "Point",
                        "coordinates": [inl_lon, inl_lat],
                    },
                    "properties": {
                        "node_id": inl_id,
                        "feature_type": "candidate_inlet",
                        "provenance": "synthetic",
                        "generation_algorithm": "MSDI_v1.0",
                        "generation_timestamp": generation_time,
                        "confidence": "unverified_inference",
                        "associated_link": link_id,
                        "ground_elevation_m": inlet_elev,
                        "assumed_parameters": {
                            "intake_type": "curb_opening_inlet",
                            "grate_length_m": 1.0,
                            "nominal_capture_capacity_cumecs": round(0.045 * capacity_factor, 3),
                            "is_engineering_assumption": True,
                        },
                        "operating_scenario": self.scenario,
                        "validation_status": "topologically_verified",
                    },
                }
                synthetic_features.append(inlet_feature)
                inlet_count += 1

        # Add node features (junctions and candidate outfalls)
        for nid, n_info in node_lookup.items():
            is_outfall = n_info["type"] == "candidate_outfall"
            if is_outfall:
                outfall_count += 1

            synthetic_features.append({
                "type": "Feature",
                "id": nid,
                "geometry": {
                    "type": "Point",
                    "coordinates": [round(n_info["coords"][0], 6), round(n_info["coords"][1], 6)],
                },
                "properties": {
                    "node_id": nid,
                    "feature_type": n_info["type"],
                    "provenance": "synthetic",
                    "generation_algorithm": "MSDI_v1.0",
                    "generation_timestamp": generation_time,
                    "confidence": "unverified_inference_boundary" if is_outfall else "unverified_inference",
                    "elevation_m": round(n_info["elevation"], 2),
                    "assumed_parameters": {
                        "invert_elevation_m": round(max(0.2, n_info["elevation"] - 1.5), 2),
                        "is_engineering_assumption": True,
                    },
                    "warning": (
                        "Hypothetical candidate outfall inferred from terrain slope descent toward coastal margin; "
                        "not a surveyed municipal flap gate." if is_outfall else None
                    ),
                    "operating_scenario": self.scenario,
                    "validation_status": "topologically_verified",
                },
            })

        result = {
            "type": "FeatureCollection",
            "provenance": "synthetic",
            "generator": "MUFNS Synthetic Drainage Inference (MSDI) v1.0",
            "disclaimer": (
                "Synthetic/inferred drainage data — not a verified map of municipal infrastructure. "
                "Do not use this layer alone for real-world safety or evacuation decisions."
            ),
            "generated_at_utc": generation_time,
            "scenario": self.scenario,
            "metrics": {
                "total_features": len(synthetic_features),
                "links_count": link_count,
                "inlets_count": inlet_count,
                "junctions_count": len(node_lookup) - outfall_count,
                "candidate_outfalls_count": outfall_count,
                "total_pipe_length_km": round(sum(f["properties"].get("length_m", 0) for f in synthetic_features) / 1000.0, 2),
                "design_standard": "BMC / CPHEEO Urban Drainage (25 mm/h design rainfall standard)",
            },
            "features": synthetic_features,
        }

        # Persist generated dataset to data/cities/mumbai/synthetic_drainage.geojson
        OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
        out_file = OUTPUT_DIR / "synthetic_drainage.geojson"
        with open(out_file, "w", encoding="utf-8") as f:
            json.dump(result, f, indent=2)

        logger.info(
            "MSDI synthetic drainage generation complete",
            links=link_count,
            inlets=inlet_count,
            outfalls=outfall_count,
            output_file=str(out_file),
        )
        return result
